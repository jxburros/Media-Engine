"""Generate native/sdxl/src/unicode_tables.rs from the Python reference environment.

The CLIP tokenizer the Python pipeline uses (transformers' slow CLIPTokenizer without ftfy) depends
on Python's `unicodedata` (control/whitespace categories, NFC), `str.lower`/`str.split` and the
`regex` module's \\p{L} / \\p{N} / \\s classes under IGNORECASE. This script records exactly those
predicates so the owned tokenizer reproduces them without a Unicode crate. Run with the reference
interpreter:  python native/sdxl/tools/gen_unicode_tables.py > native/sdxl/src/unicode_tables.rs
"""

import sys
import unicodedata

import regex

MAX = 0x110000


def chars():
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp


def ranges(pred):
    out, start, prev = [], None, None
    for cp in chars():
        if pred(cp):
            if start is not None and cp == prev + 1:
                prev = cp
                continue
            if start is not None:
                out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def emit_ranges(name, rs):
    print(f"pub static {name}: &[(u32, u32)] = &[")
    line = []
    for a, b in rs:
        line.append(f"(0x{a:X}, 0x{b:X})")
        if len(line) == 6:
            print("    " + ", ".join(line) + ",")
            line = []
    if line:
        print("    " + ", ".join(line) + ",")
    print("];")


def is_control(cp):
    c = chr(cp)
    if c in "\t\n\r":
        return False
    return unicodedata.category(c).startswith("C")


def is_whitespace(cp):
    c = chr(cp)
    if c in " \t\n\r":
        return True
    return unicodedata.category(c) == "Zs"


LETTER = regex.compile(r"[\p{L}]", regex.IGNORECASE)
NUMBER = regex.compile(r"[\p{N}]", regex.IGNORECASE)
OTHER = regex.compile(r"[^\s\p{L}\p{N}]", regex.IGNORECASE)


def main():
    print("// @generated by native/sdxl/tools/gen_unicode_tables.py — do not edit.")
    print(f"// Python {sys.version.split()[0]}, unicodedata {unicodedata.unidata_version}, regex {regex.__version__}.")
    print("#![allow(clippy::all)]")
    print()
    emit_ranges("CONTROL", ranges(is_control))
    emit_ranges("WHITESPACE", ranges(is_whitespace))
    emit_ranges("PY_SPACE", ranges(lambda cp: chr(cp).isspace()))
    emit_ranges("RE_LETTER", ranges(lambda cp: LETTER.fullmatch(chr(cp)) is not None))
    emit_ranges("RE_NUMBER", ranges(lambda cp: NUMBER.fullmatch(chr(cp)) is not None))
    emit_ranges("RE_OTHER", ranges(lambda cp: OTHER.fullmatch(chr(cp)) is not None))

    # str.lower: single-codepoint results go in LOWER; anything longer in LOWER_MULTI.
    single, multi = [], []
    for cp in chars():
        low = chr(cp).lower()
        if low == chr(cp) or cp == 0x3A3:
            continue
        if len(low) == 1:
            single.append((cp, ord(low)))
        else:
            multi.append((cp, [ord(x) for x in low]))
    print("pub static LOWER: &[(u32, u32)] = &[")
    for i in range(0, len(single), 6):
        print("    " + ", ".join(f"(0x{a:X}, 0x{b:X})" for a, b in single[i : i + 6]) + ",")
    print("];")
    print("pub static LOWER_MULTI: &[(u32, &[u32])] = &[")
    for a, bs in multi:
        print(f"    (0x{a:X}, &[" + ", ".join(f"0x{b:X}" for b in bs) + "]),")
    print("];")

    # Final-sigma context predicates, probed through str.lower itself.
    def probe(s):
        return s.lower()

    ignorable, cased = [], []
    for cp in chars():
        x = chr(cp)
        p1 = probe(x + "Σ").endswith("ς")
        p2 = probe("A" + x + "Σ").endswith("ς")
        p3 = probe("AΣ" + x)[1] == "ς"
        if p1:
            cased.append(cp)
        elif p2 and p3:
            ignorable.append(cp)
    ci, cc = set(ignorable), set(cased)
    emit_ranges("CASE_IGNORABLE", ranges(lambda cp: cp in ci))
    emit_ranges("CASED", ranges(lambda cp: cp in cc))

    # NFC: canonical combining classes, full canonical decompositions, primary composites.
    ccc = []
    for cp in chars():
        k = unicodedata.combining(chr(cp))
        if k:
            ccc.append((cp, k))
    runs = []
    for cp, k in ccc:
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == k:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, k])
    print("pub static CCC: &[(u32, u32, u8)] = &[")
    for i in range(0, len(runs), 5):
        print("    " + ", ".join(f"(0x{a:X}, 0x{b:X}, {k})" for a, b, k in runs[i : i + 5]) + ",")
    print("];")
    decomp, flat = [], []
    for cp in chars():
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            decomp.append((cp, len(flat), len(d)))
            flat.extend(ord(x) for x in d)
    print("pub static DECOMP: &[(u32, u16, u8)] = &[")
    for i in range(0, len(decomp), 5):
        print("    " + ", ".join(f"(0x{a:X}, {o}, {n})" for a, o, n in decomp[i : i + 5]) + ",")
    print("];")
    print("pub static DECOMP_DATA: &[u32] = &[")
    for i in range(0, len(flat), 10):
        print("    " + ", ".join(f"0x{x:X}" for x in flat[i : i + 10]) + ",")
    print("];")
    comp = []
    for cp in chars():
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        raw = unicodedata.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) != 2:
            continue
        if unicodedata.normalize("NFC", chr(cp)) != chr(cp):
            continue
        comp.append((parts[0], parts[1], cp))
    comp.sort()
    print("pub static COMPOSE: &[(u32, u32, u32)] = &[")
    for i in range(0, len(comp), 4):
        print("    " + ", ".join(f"(0x{a:X}, 0x{b:X}, 0x{c:X})" for a, b, c in comp[i : i + 4]) + ",")
    print("];")


main()
